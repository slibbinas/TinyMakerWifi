// Trust anchors for the slicer manifest fetch (0.17 SL-mod, 08-22).
//
// WHY THIS FILE EXISTS. The printer decides which bytes may land on its SD card
// by the checksums it pulls from our GitHub Pages. Until now that fetch ran with
// setInsecure(), like every other HTTPS call in this firmware - which means the
// trust anchor was not "GitHub" but "whoever answers as slibbinas.github.io on
// this network". Since the slicer files are JAVASCRIPT AND WASM that the
// dashboard then runs on its own origin, and since the copy is automatic and
// silent, that was the one place where the shortcut actually bought an attacker
// something (security review 08-22). Verifying the manifest is enough to close
// it: the 3.6 MB payload is only accepted if it matches a checksum that came
// over a verified connection.
//
// WHAT IS IN HERE. Two anchors, both taken live and both verified with openssl
// to validate the *.github.io leaf on their own:
//
//   ISRG Root X1      self-signed, valid to 2035-06-04
//                     SHA-256 96:BC:EC:06:26:49:76:F3:74:60:77:9A:CF:28:C5:A7:
//                             CF:E8:A3:C0:AA:E1:1A:8F:FC:EE:05:C0:BD:DF:08:C6
//   ISRG Root YR      cross-signed by X1, valid to 2032-09-02
//                     SHA-256 07:26:39:D0:B1:40:D5:BF:FA:E1:6A:D9:C3:F6:CC:60:
//                             86:04:06:21:F5:1E:E6:1A:6D:46:A8:91:5C:07:CF:76
//
// The chain served today is *.github.io <- Let's Encrypt YR1 <- ISRG Root YR,
// and either anchor terminates it. Two are kept so that dropping the cross-sign
// does not break us on its own.
//
// WHEN THIS BREAKS. If GitHub Pages ever moves off Let's Encrypt, the fetch
// starts answering "could not verify GitHub" and slicer updates stop - the copy
// already on the card keeps working, so nothing dies, but this file has to be
// refreshed. That fragility is the known price of this approach; the durable fix
// is to sign our own manifest with our own key (plan 1.1), which does not depend
// on anyone else's certificate at all.
//
// Refresh with:
//   openssl s_client -connect slibbinas.github.io:443 \
//       -servername slibbinas.github.io -showcerts
